// THIS FILE IS THE CONTRACT between this extension's Go backend and its browser panel, which lives in
// easydev-org/easyagent-sandbox-ext-ui and is served by easyagent-ext-ui-host. It replaces a set of
// hand-written JSON routes whose shapes were `map[string]any` literals — the same arrangement that
// produced an empty file tree in another extension when a route emitted `Path` and the panel read
// `path`.
//
// WHAT IS NOT HERE, AND WHY: the screen stream. `GET /ext/sandbox/api/sandboxes/{name}/screen` is a
// WebSocket carrying H.264 access units straight from easystream to the browser's VideoDecoder.
// Wrapping those in protobuf messages would add an encode and a decode per frame and force the panel
// to reassemble frame boundaries itself, for no benefit — a WebSocket is the right transport for a
// media stream, and it already works. It stays a plain proxied route, documented in the README.

